await ev(() => goPhaseInternal(2)); await sleep(1500);
const has = await ev(() => { return !!document.querySelector('button[onclick*="grProponiBozza"]'); }); 
ok(has, 'pulsante «Proponi bozza dalla griglia» in 1.3');
