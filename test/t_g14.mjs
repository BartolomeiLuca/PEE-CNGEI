import { FakeDB, serve, launch, person, sleep, ok, summary, loginAs } from './harness.mjs';
const engine = process.argv[2] || 'chromium';
process.env.SITE = '/tmp/site_sh';
const base = (await serve()) + 'anteprima/';
const br = await launch(engine);
const db = new FakeDB(); const pa = await person(br, db, {ctx:{viewport:{width:1280, height:800}}}); const P = pa.page, ev = (f, a) => P.evaluate(f, a);
const u = db.addUser('anna@x.it', 'password123', 'Anna Verdi');
db.t.pee_profili.push({user_id:u.id, nome:'Anna Verdi', ruolo:'cu', branca:'L', sezione:'Pesaro', gruppo:'1', dashboard:{}});
const mk = (id, B) => ({id, user_id:u.id, anno:2026, titolo:'P' + id, meta:{mode:'giovani', fascia:B, tipo:'AN', nome:'U'}, data:{v:1, MODE:'giovani', FASCIA:B, UNIT_NAME:'U', obs:{}, scheda:{tipoProgetto:'AN', annoScout:'2026-27', pp:{}}}, created_at:'2026-10-20T10:00:00Z', updated_at:'2026-10-26T10:00:00Z'});
db.t.pee_archivi.push(mk('pL', 'L'), mk('pE', 'E'));
await loginAs(P, base, u); await sleep(1200);
const th = () => ev(() => document.body.getAttribute('data-theme'));
await ev(() => shOpen('pL', 0)); await sleep(3000);
ok(await th() === 'L', 'dentro il progetto Branco: tema L');
await ev(() => shProfileOpen()); await sleep(600);
ok(await th() === null, 'profilo aperto dal progetto: colori neutri (nessun tema)');
const hb = await ev(() => getComputedStyle(document.querySelector('.sh-top')).backgroundColor);
ok(hb !== 'rgb(31, 29, 0)' && hb !== 'rgb(240, 230, 3)', 'intestazione del profilo non scura né gialla: ' + hb);
await ev(() => shGoHome()); await sleep(800);
ok(await th() === null, 'elenco progetti: colori neutri');
await ev(() => shOpen('pE', 0)); await sleep(3000);
ok(await th() === 'E', 'apro un progetto Esploratori: tema E (non resta L)');
await ev(() => shProfileOpen()); await sleep(500);
await P.click('.sh-wrap button:has-text("Annulla")'); await sleep(600);
ok(await th() === null, 'Annulla nel profilo porta all’elenco: colori neutri');
await ev(() => shOpen('pE', 0)); await sleep(2500);
ok(await th() === 'E', 'riaprendo il progetto torna il tema E');
ok(!pa.errors.length, 'nessun errore JS' + (pa.errors.length ? ': ' + pa.errors.slice(0, 3).join(' | ') : ''));
const f = summary(); await br.close(); process.exit(f ? 1 : 0);
