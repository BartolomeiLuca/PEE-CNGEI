import { FakeDB, serve, launch, person, sleep, ok, summary } from './harness.mjs';
process.env.KEEPCLOSED = '1';
const engine = process.argv[2] || 'chromium';
const base = await serve(); const db = new FakeDB(); const br = await launch(engine);
const pa = await person(br, db); const P = pa.page, ev = (f, a) => P.evaluate(f, a);
await P.goto(base); await ev(() => localStorage.setItem('bussola_tour_v3', '1')); await P.reload(); await sleep(800);
await P.locator(':is(a,button):visible', {hasText:'Apri un progetto di esempio'}).first().click(); await sleep(1500);
await ev(() => gGo('3')); await sleep(600);
const n = await ev(() => document.querySelectorAll('.pcx').length);
ok(n >= 1 && await ev(() => [...document.querySelectorAll('.pcx')].every(c => c.classList.contains('closed'))), 'Sezione 3: tutti i percorsi si presentano chiusi (' + n + ')');
ok(await ev(() => !document.querySelector('.pcx .pcx-body').offsetParent), 'Sezione 3: il contenuto del percorso non si vede da chiuso');
await P.click('#pc-card-0 .pcx-hd'); await sleep(300);
ok(await ev(() => !document.getElementById('pc-card-0').classList.contains('closed') && !!document.querySelector('#pc-card-0 .pcx-body').offsetParent), 'si apre con un clic');
ok(await ev(() => [...document.querySelectorAll('#pc-card-0 details[id^="att-"]')].every(d => !d.open)), 'Attività 1, 2 e 3 chiuse');
await P.click('#att-0-1 > summary'); await sleep(200);
await ev(() => { renderValuation(); }); await sleep(400);
ok(await ev(() => !document.getElementById('pc-card-0').classList.contains('closed') && document.getElementById('att-0-1').open && !document.getElementById('att-0-0').open), 'dopo un ridisegno resta aperto ciò che avevo aperto');
await ev(() => { pcxToggle(0); tlGo(0, 2); }); await sleep(300);
ok(await ev(() => !document.getElementById('pc-card-0').classList.contains('closed') && document.getElementById('att-0-2').open), 'dalla linea del tempo si apre il percorso giusto');
ok(!pa.errors.length, 'nessun errore JS' + (pa.errors.length ? ': ' + pa.errors.slice(0, 3).join(' | ') : ''));
const f = summary(); await br.close(); process.exit(f ? 1 : 0);
