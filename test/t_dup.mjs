// Correzione 12: «Duplica» in archivio
import { FakeDB, serve, launch, person, loginAs, sleep, ok, summary } from './harness.mjs';
const engine = process.argv[2] || 'chromium';
const base = await serve(); const db = new FakeDB(); db.sql13 = true;
const A = db.addUser('anna@x.it', 'password123', 'Anna Rossi');
const br = await launch(engine);
const pa = await person(br, db), P = pa.page, ev = (f, a) => P.evaluate(f, a);
await loginAs(P, base, A); await ev(() => exStart()); await sleep(3000);
await ev(async () => { await dbInvite(CL.ctx.id, 'bruno@x.it', 'collaboratore'); scheda.pp.numTot = '24'; saveData(true); }); await sleep(2500);
const src = db.t.pee_archivi.find(r => /Esempio/.test(r.titolo));
await ev(() => clOpen()); await sleep(1500);
const row = P.locator('#cl-arclist .cl-row', {hasText: src.titolo}).first();
ok(await row.locator('button', {hasText:'Duplica'}).count() === 1, 'in archivio c’è «Duplica» accanto al progetto');
await row.locator('button', {hasText:'Duplica'}).click(); await sleep(300);
const sel = P.locator(`#cl-dup-y-${src.id}`);
ok(await sel.isVisible() && (await sel.locator('option').allTextContents()).join('|') === `${src.anno} (stesso anno)|${src.anno + 1} (anno successivo)`, 'chiede l’anno: stesso o successivo');
await sel.selectOption(String(src.anno + 1));
await P.locator(`#cl-dup-${src.id} button`, {hasText:'Crea la copia'}).click(); await sleep(2000);
const cp = db.t.pee_archivi.find(r => r.titolo === src.titolo + ' (copia)');
ok(!!cp && cp.anno === src.anno + 1 && cp.user_id === A.id, 'copia creata nell’anno scelto: ' + (cp ? cp.anno + ' · ' + cp.titolo : 'nessuna'));
const strip = d => JSON.stringify(Object.assign({}, d, {ts:0}));
ok(cp && strip(cp.data) === strip(db.t.pee_archivi.find(r => r.id === src.id).data), 'copia identica dei dati (compreso l’ultimo lavoro)');
ok(cp && !db.t.pee_membri.some(m => m.archivio_id === cp.id), 'inviti e condivisioni non copiati');
ok(await P.locator('#cl-arclist .cl-row', {hasText: src.titolo + ' (copia)'}).count() === 1, 'la copia compare subito in archivio');
await P.locator(`#cl-arclist button[onclick*="clDupAsk('${src.id}'"]`).click(); await sleep(300);
await P.locator(`#cl-dup-${src.id} button`, {hasText:'Crea la copia'}).click(); await sleep(2000);
ok(db.t.pee_archivi.some(r => r.titolo === src.titolo + ' (copia)' && r.anno === src.anno), 'stesso anno: «(copia)» anche lì');
await ev(id => clOpenProject(id), cp.id); await sleep(3500);
ok(await ev(() => CL.ctx && CL.ctx.titolo) === src.titolo + ' (copia)' && await ev(() => scheda.pp.numTot) === '24', 'la copia si apre e ha i dati');
ok(db.t.pee_archivi.find(r => r.id === src.id).titolo === src.titolo, 'l’originale resta com’era');
ok(!pa.errors.length, 'nessun errore JS' + (pa.errors.length ? ': ' + pa.errors.slice(0, 3).join(' | ') : ''));
const f = summary(); await br.close(); process.exit(f ? 1 : 0);
